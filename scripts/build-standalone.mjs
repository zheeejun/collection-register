import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import { build } from 'vite'

const root = fileURLToPath(new URL('../', import.meta.url))
const cssPath = new URL('../src/collection-register-standalone/collection-register-standalone.generated.css', import.meta.url)

const result = await build({
  configFile: false,
  root,
  plugins: [tailwindcss()],
  build: {
    write: false,
    rollupOptions: {
      input: fileURLToPath(new URL('../src/collection-register-standalone/collection-register-standalone.css', import.meta.url)),
    },
  },
})
const outputs = Array.isArray(result) ? result : [result]
const css = outputs.flatMap(output => output.output)
  .filter(asset => asset.type === 'asset' && asset.fileName.endsWith('.css'))
  .map(asset => asset.source)
  .join('\n')
if (!css) throw new Error('No standalone CSS was generated')

await writeFile(cssPath, `/* Generated by npm run build:standalone. Edit collection-register-standalone.css, then rebuild. */\n${css}\n`)
console.log('Generated collection-register-standalone.generated.css')
